// Maze wall glyphs for pacman.s. Run from the repo root:
//   node tools/gen-maze-glyphs.mjs
//
// A box-drawing character is defined by which of its four sides connect,
// so these glyphs are generated from that mask rather than drawn: a 2 px
// rail runs from the cell centre out to each connected edge. Neighbouring
// characters therefore meet flush at the cell boundary by construction -
// a joint is part of the character, not something the program works out
// from its neighbours, so a corner cannot come out broken.
import { readFileSync, writeFileSync } from 'node:fs';

const LO = 0o263; // '│', where the pseudographics we use start
const HI = 0o332; // '┌'
const DOOR = 0o315; // '═', the ghost house gate

// code page 437 code -> connected sides
const SIDES = {
  0o263: 'UD', // │
  0o264: 'UDL', // ┤
  0o277: 'DL', // ┐
  0o300: 'UR', // └
  0o301: 'ULR', // ┴
  0o302: 'DLR', // ┬
  0o303: 'UDR', // ├
  0o304: 'LR', // ─
  0o305: 'UDLR', // ┼
  0o331: 'UL', // ┘
  0o332: 'DR', // ┌
};

const blank = () => [...Array(16)].map(() => Array(16).fill(0));
const glyphs = [];
const index = new Array(HI - LO + 1).fill(0);

for (const [code, sides] of Object.entries(SIDES)) {
  const g = blank();
  const rail = (y0, y1, x0, x1) => {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g[y][x] = 1;
  };
  rail(7, 8, 7, 8); // the centre, so a lone arm still has a hub
  if (sides.includes('U')) rail(0, 8, 7, 8);
  if (sides.includes('D')) rail(7, 15, 7, 8);
  if (sides.includes('L')) rail(7, 8, 0, 8);
  if (sides.includes('R')) rail(7, 8, 7, 15);
  glyphs.push({ code: Number(code), rows: g });
}

// The gate: dashed, on the same rails as the wall it interrupts. The
// period divides 16 with a mark at each end, so the dashes meet flush
// across a cell boundary just as the solid rails do.
{
  const g = blank();
  for (let x = 0; x < 16; x++) if (x % 5 < 3) g[7][x] = g[8][x] = 1;
  glyphs.push({ code: DOOR, rows: g });
}

glyphs.forEach((gl, i) => {
  index[gl.code - LO] = i + 1;
});
const doorSlot = glyphs.findIndex((g) => g.code === DOOR) + 1;

const oct = (v) => v.toString(8);
const out = [];
out.push(`GDOOR   = ${doorSlot}.`);
out.push(`; character code -> glyph number (0 = not a wall); base is 0${oct(LO)}`);
out.push('GIDX:   .BYTE ' + index.map(oct).join(', '));
out.push('        .EVEN');
out.push('; 16x16 glyphs, two bytes per row, bit 0 leftmost');
out.push('GLYPHS:');
for (const gl of glyphs) {
  out.push(`\t; 0${oct(gl.code)}`);
  for (const row of gl.rows) {
    let w = 0;
    row.forEach((b, i) => {
      if (b) w |= 1 << i;
    });
    out.push(`\t.BYTE ${oct(w & 0xff)}, ${oct((w >> 8) & 0xff)}`);
  }
}

const path = process.argv[2] ?? 'programs/pacman.s';
const src = readFileSync(path, 'utf8');
const BEGIN = '; --- maze glyphs begin (generated by gen-maze-glyphs.mjs, do not edit) ---';
const END = '; --- maze glyphs end ---';
const a = src.indexOf(BEGIN);
const b = src.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers not found in ' + path);
writeFileSync(path, src.slice(0, a + BEGIN.length) + '\n' + out.join('\n') + '\n' + src.slice(b));
console.log(`spliced ${glyphs.length} glyphs, door is glyph ${doorSlot}`);
